// Turns the Academy design (docs/iip-academy/design/iip-academy-reference.html) into the portal's Academy assets:
//   components/academy/academy.css          the design's CSS, every selector scoped under .iipa so nothing leaks into IIP
//   components/academy/icons.generated.ts   the design's 50 icon paths, as they are
//   public/academy/hero.webp                the hero photograph embedded in the design
//
//   node scripts/build-academy-assets.mjs
//
// Regenerable from the reference, which stays in the repository. The design is the authority: change the reference
// (or this script), never the generated files.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const portal = path.resolve(here, "..");
const repo = path.resolve(portal, "..", "..");
const html = fs.readFileSync(path.join(repo, "docs", "iip-academy", "design", "iip-academy-reference.html"), "utf8");

// ---------------------------------------------------------------- CSS

const css = /<style>([\s\S]*?)<\/style>/.exec(html)[1].replace(/\/\*[\s\S]*?\*\//g, "");
const ROOT = ".iipa";

/** Splits "a{...}b{...}" into top-level [prelude, body] pairs. */
function topLevel(text) {
  const rules = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf("{", i);
    if (open < 0) break;
    const prelude = text.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < text.length && depth > 0) {
      if (text[j] === "{") depth++;
      else if (text[j] === "}") depth--;
      j++;
    }
    rules.push([prelude, text.slice(open + 1, j - 1)]);
    i = j;
  }
  return rules;
}

function scopeSelector(selector) {
  const s = selector.trim();
  if (s === ":root") return ROOT;
  if (s === "*") return `${ROOT}, ${ROOT} *`;
  if (s === "html") return null;
  if (s === "body") return ROOT;
  const body = /^body((?:\.[\w-]+|\[[^\]]+\])*)\s*(.*)$/.exec(s);
  if (body && s.startsWith("body")) return `${ROOT}${body[1]}${body[2] ? " " + body[2] : ""}`;
  return `${ROOT} ${s}`;
}

const keyframes = new Set(topLevel(css).filter(([p]) => p.startsWith("@keyframes")).map(([p]) => p.split(/\s+/)[1]));

function scopeDeclarations(body) {
  let out = body
    .replace(/font-family:\s*'Plus Jakarta Sans'/g, "font-family:var(--font-jakarta),'Plus Jakarta Sans'")
    .replace(/animation:\s*([\w-]+)/g, (m, name) => (keyframes.has(name) ? `animation:iipa-${name}` : m));
  return out;
}

function scopeBlock(rules) {
  const lines = [];
  for (const [prelude, body] of rules) {
    if (prelude.startsWith("@media")) {
      lines.push(`${prelude}{`, ...scopeBlock(topLevel(body)), "}");
    } else if (prelude.startsWith("@keyframes")) {
      const name = prelude.split(/\s+/)[1];
      lines.push(`@keyframes iipa-${name}{${body}}`);
    } else {
      const selectors = prelude.split(",").map(scopeSelector).filter(Boolean);
      if (selectors.length) lines.push(`${selectors.join(",")}{${scopeDeclarations(body)}}`);
    }
  }
  return lines;
}

const scoped = scopeBlock(topLevel(css)).join("\n");

// The design was written for a bare page. Inside the portal, the portal's own base styles (Tailwind's reset) would
// change a few elements, so the design's browser defaults are restored for the Academy only. These come first so every
// rule of the design still wins over them.
const compat = `
${ROOT} ul,${ROOT} ol{list-style:revert}
${ROOT} h1,${ROOT} h2,${ROOT} h3,${ROOT} h4{font-size:revert;font-weight:revert}
${ROOT} img,${ROOT} svg{max-width:none;height:revert}
${ROOT} hr{height:auto;color:inherit}
${ROOT} textarea,${ROOT} input,${ROOT} select{border-radius:0;background-color:transparent}
${ROOT} button{background:none;border:0}
${ROOT}{overflow-x:clip}
`;

const header = `/* Generated by scripts/build-academy-assets.mjs from docs/iip-academy/design/iip-academy-reference.html. Do not edit. */\n`;
const cssOut = path.join(portal, "components", "academy", "academy.css");
fs.mkdirSync(path.dirname(cssOut), { recursive: true });
fs.writeFileSync(cssOut, header + compat + scoped + "\n", "utf8");

// ---------------------------------------------------------------- icons

const iconBlock = /const IC=(\{[\s\S]*?\});\s*function ic/.exec(html)[1];
const icons = JSON.parse(iconBlock);
const iconOut = path.join(portal, "components", "academy", "icons.generated.ts");
fs.writeFileSync(
  iconOut,
  `// Generated by scripts/build-academy-assets.mjs from the Academy design. Do not edit.\n` +
    `export const ICON_PATHS: Record<string, string> = ${JSON.stringify(icons, null, 1)};\n`,
  "utf8",
);

// ---------------------------------------------------------------- hero image

const hero = /const JANE_HERO='data:image\/webp;base64,([^']+)'/.exec(html)[1];
const heroOut = path.join(portal, "public", "academy", "hero.webp");
fs.writeFileSync(heroOut, Buffer.from(hero, "base64"));

for (const file of ["iip-academy-logo.svg", "iip-logo.svg"]) {
  fs.copyFileSync(path.join(repo, "docs", "iip-academy", "design", file), path.join(portal, "public", "academy", file));
}

const kb = (file) => (fs.statSync(file).size / 1024).toFixed(0);
console.log(`academy.css ${kb(cssOut)} KB, icons ${Object.keys(icons).length}, hero.webp ${kb(heroOut)} KB`);
